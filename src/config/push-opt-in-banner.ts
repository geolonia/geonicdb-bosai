/**
 * ヘッダー上部に出す「通知をオンにすることをおすすめします」帯の設定。
 *
 * 運用でいじるつまみはここだけ。コンポーネント側には数値を直書きしない。
 */

/**
 * 帯を閉じてから再表示するまでの日数。
 *
 * 短くすると通知の到達率は上がるが、住民から見れば毎回出る邪魔な帯になる。
 * 既定は 1 週間。自治体の運用方針に合わせて変更してよい。
 */
export const PUSH_OPT_IN_BANNER_DISMISS_DAYS = 7;

/** 1 日のミリ秒。 */
const MS_PER_DAY = 24 * 60 * 60 * 1000;

/** 再表示までの猶予（ミリ秒）。`PUSH_OPT_IN_BANNER_DISMISS_DAYS` から導出する。 */
export const PUSH_OPT_IN_BANNER_DISMISS_MS =
  PUSH_OPT_IN_BANNER_DISMISS_DAYS * MS_PER_DAY;

/*
 * 表示の契機について（つまみではないのでここには定数を置かない）
 *
 * この帯はヘッダーより上の文書フローに入るため、差し込むとページ全体が
 * 下へずれる。out-of-flow にはできない（アクセシビリティ方針で
 * 「固定オーバーレイは置かない」と公表済み）。そのため
 * **初回のユーザー入力（click / keydown）まで出さない** ことで、ずれを
 * 入力から 500ms 以内に収め CLS に計上させない。
 *
 * 無操作タイマーでの表示は行わない。`AddToHomeScreenPrompt` の
 * `A2HS_CHROMIUM_IDLE_MS` は `position: fixed` + body の padding 予約が
 * 前提で「出しても何もずれない」ため成立する手であり、文書フローに載る
 * この帯には流用できない（流用すると読んでいる最中に無入力でページが
 * 飛ぶ = 実ユーザーの CLS）。
 *
 * 代償: 一度も tap / キー入力しない利用者には帯が出ない。ただしその利用者は
 * 帯が出ても通知をオンにできないので、失うものは無い（フッターのトグルは常設）。
 *
 * pointerdown ではなく click で出すのは、押下時点でずらすと pointerup が
 * 別要素に当たり利用者の最初のタップが無効になるため。キーボードは逆に
 * keydown（既定動作より前）で出す。keyup だと Tab の移動先が確定した後に
 * 帯が挿入され、その回の順次移動で帯が飛ばされる。
 */
